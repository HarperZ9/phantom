#[cfg(test)]
mod tests {
    use super::*;

    // Versions are positive and match the ones referenced in text.
    #[test]
    fn versions_are_current() {
        assert_eq!(PRIVACY_NOTICE_VERSION, 1);
        assert_eq!(TOU_VERSION, 1);
        assert!(PRIVACY_NOTICE.contains("(v1)"));
        assert!(TOU.contains("(v1)"));
    }

    // Anchor the enforcement claims: the text makes specific
    // promises the phone_home module implements. If either drifts,
    // these tests break loudly.
    #[test]
    fn privacy_notice_mentions_disable_command() {
        assert!(PRIVACY_NOTICE.contains("phantom config set phone_home_enabled false"));
    }

    #[test]
    fn privacy_notice_promises_no_fingerprint() {
        assert!(
            PRIVACY_NOTICE.contains("does not send") || PRIVACY_NOTICE.contains("DOES NOT SEND")
        );
        assert!(PRIVACY_NOTICE.contains("fingerprint"));
    }

    #[test]
    fn tou_mentions_revocation_and_appeal() {
        assert!(TOU.contains("revoke"));
        assert!(TOU.contains("appeal"));
    }
}
