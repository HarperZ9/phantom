//! Legal text and version pins.
//!
//! Two documents live here as compiled-in constants: the privacy
//! notice (what phone-home sends) and the terms of use (what a
//! customer agrees to at activation). Both carry a version integer;
//! bumping it forces re-acknowledgment on the next `activate` so a
//! material change to either document is confirmed, not silently
//! carried over.
//!
//! The text is written to be read by the operator. It is not a
//! substitute for counsel-drafted terms, but every claim it makes
//! about behavior is enforced by code:
//!
//! - "opaque license identifier" — `phone_home::license_serial_for`
//!   is an 8-hex HMAC of the key; not reversible.
//! - "does not include hardware fingerprint" — the payload struct
//!   in `phone_home::PhoneHomePayload` has no fingerprint field;
//!   tests verify.
//! - "recorded locally so you can audit" — `phone_home::read_log`
//!   returns every call ever made, signed.
//! - "may revoke your license upon receipt of credible information"
//!   — vendor tooling produces `{"revoked": true}` responses that
//!   the tripwire module acts on.

/// Bumped when the privacy notice text materially changes. Users
/// whose stored `privacy_notice_version` is less than this are
/// re-prompted on next activate.
pub const PRIVACY_NOTICE_VERSION: u32 = 1;

/// Bumped when the terms-of-use text materially changes.
pub const TOU_VERSION: u32 = 1;

pub const PRIVACY_NOTICE: &str = r#"PHANTOM PRIVACY NOTICE (v1)
============================

Phantom performs a periodic license callback ("phone-home") to
verify that your license is still valid. This notice describes
exactly what that call sends and how you can disable it.

WHAT EACH CALL SENDS
--------------------
- An opaque license identifier (an 8-hex HMAC hash of your key;
  your key cannot be recovered from it)
- Your license tier (Free / Pro / Enterprise)
- The Phantom version you are running
- The wall-clock time of the call, in seconds
- A count of any anti-tamper events recorded on this install
- A cryptographic proof-of-possession derived from your license
  key. The endpoint uses it to distinguish a legitimate install
  from an attacker who scraped your license serial.

WHAT EACH CALL DOES NOT SEND
----------------------------
- Your machine hardware fingerprint
- The contents of any profile you have generated
- The seeds you used to generate profiles
- Your name, email, IP address (except as visible at the TCP
  layer to the endpoint), or any other personally identifying
  data Phantom does not need to validate your license

FREQUENCY AND TRANSPORT
-----------------------
- At most once every 24 hours per install
- Sent via the standard `curl` binary on your system so the URL
  and body are visible in `ps` output and any audit log you keep
- Failures (offline, blocked, timeout) do not degrade the tool
- Every call is recorded locally under
  <data_dir>/.phone_home_log so you can audit exactly what was
  sent and when — that file never leaves your machine unless you
  choose to share it

HOW TO DISABLE
--------------
    phantom config set phone_home_enabled false

Disabling means your install will not send license-validation
callbacks. Your license remains valid until it expires; the
endpoint just will not hear from you.
"#;

